CREATE TABLE sistemas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(40) NOT NULL UNIQUE,
    nombre VARCHAR(100) NOT NULL,
    dominio VARCHAR(150),
    activo BOOLEAN NOT NULL
);

CREATE TABLE permisos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(50) NOT NULL UNIQUE,
    descripcion VARCHAR(150)
);

CREATE TABLE modulos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(50) NOT NULL,
    nombre VARCHAR(100) NOT NULL,
    descripcion VARCHAR(180),
    sistema_id BIGINT NOT NULL REFERENCES sistemas(id),
    modulo_padre_id BIGINT REFERENCES modulos(id),
    ruta VARCHAR(150),
    icono VARCHAR(50),
    orden INTEGER NOT NULL,
    activo BOOLEAN NOT NULL,
    CONSTRAINT uk_modulos_codigo_sistema UNIQUE (codigo, sistema_id)
);

CREATE TABLE roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(50) NOT NULL,
    descripcion VARCHAR(150),
    activo BOOLEAN NOT NULL,
    sistema_id BIGINT NOT NULL REFERENCES sistemas(id),
    CONSTRAINT uk_roles_nombre_sistema UNIQUE (nombre, sistema_id)
);

CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    email VARCHAR(100) NOT NULL UNIQUE,
    enabled BOOLEAN NOT NULL
);

CREATE TABLE usuario_roles (
    usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
    rol_id BIGINT NOT NULL REFERENCES roles(id),
    CONSTRAINT uk_usuario_roles UNIQUE (usuario_id, rol_id)
);

CREATE TABLE roles_modulos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rol_id BIGINT NOT NULL REFERENCES roles(id),
    modulo_id BIGINT NOT NULL REFERENCES modulos(id),
    CONSTRAINT uk_roles_modulos UNIQUE (rol_id, modulo_id)
);

CREATE TABLE roles_modulos_permisos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rol_id BIGINT NOT NULL REFERENCES roles(id),
    modulo_id BIGINT NOT NULL REFERENCES modulos(id),
    permiso_id BIGINT NOT NULL REFERENCES permisos(id),
    CONSTRAINT uk_roles_modulos_permisos UNIQUE (rol_id, modulo_id, permiso_id)
);
